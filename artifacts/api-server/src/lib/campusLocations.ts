// ─── Lookup helpers ─────────────────────────────────────────────────────────

/** Find a location by fuzzy-matching against name and all aliases */
export function findLocationByName(query: string): CampusLocation | null {
  const q = query.toLowerCase().trim();
  if (!q) return null;

  // Exact alias or name match first
  for (const loc of CAMPUS_LOCATIONS) {
    if (loc.name.toLowerCase() === q) return loc;
    if (loc.aliases.some(a => a.toLowerCase() === q)) return loc;
  }

  // Partial match — alias fully contained in query
  for (const loc of CAMPUS_LOCATIONS) {
    if (loc.aliases.some(a => q.includes(a.toLowerCase()))) return loc;
  }

  // Partial match — query contained in name or alias
  for (const loc of CAMPUS_LOCATIONS) {
    if (loc.name.toLowerCase().includes(q)) return loc;
    if (loc.aliases.some(a => a.toLowerCase().includes(q))) return loc;
  }

  return null;
}

/** Detect if a message is requesting navigation / location information */
export function isNavigationIntent(text: string): boolean {
  const t = text.toLowerCase();
  const patterns = [
    /where is (the |a |an )?/,
    /take me to/,
    /navigate (me )?to/,
    /how (do i|can i) (get|go) to/,
    /directions? to/,
    /show me (the |a |an )?/,
    /find (the |a |an )?/,
    /locate (the |a |an )?/,
    /i('m| am) (standing |at |near )/,
    /i need to (get to|find|go to)/,
    /how far is/,
    /nearest (atm|bank|canteen|food|hospital|pharmacy)/,
    /i('m| am) trying to find/,
    /can you (show|take) me/,
    /walk me to/,
    /lead me to/,
    /get to (the |a |an )?/,
    /going to (the |a |an )?/,
    /looking for (the |a |an )?/,
  ];
  return patterns.some(p => p.test(t));
}
